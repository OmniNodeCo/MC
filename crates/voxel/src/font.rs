/// Atlas cell containing the (upper case) glyph for `c`.
pub fn glyph_cell(c: char) -> u32 {
    let upper = c.to_ascii_uppercase() as u32;
    if has_glyph(upper) {
        FONT_CELL_BASE + (upper - 32)
    } else {
        FONT_CELL_BASE + ('?' as u32 - 32)
    }
}

fn has_glyph(code: u32) -> bool {
    GLYPHS.iter().any(|(c, _)| *c as u32 == code)
}

/// Paint the font block into the atlas. Unsupported ASCII characters are
/// filled with the `?` glyph so nothing renders as an invisible cell.
pub fn paint_glyphs(atlas: &mut [u8]) {
    let question = GLYPHS
        .iter()
        .find(|(c, _)| *c == '?')
        .map(|(_, rows)| *rows)
        .unwrap_or(["#####"; 7]);

    for code in 32u32..=126 {
        let cell = FONT_CELL_BASE + (code - 32);
        let rows = GLYPHS
            .iter()
            .find(|(c, _)| *c as u32 == code)
            .map(|(_, rows)| *rows)
            .unwrap_or(question);
        paint_cell(atlas, cell, &rows);
    }
}

fn paint_cell(atlas: &mut [u8], cell: u32, rows: &[&str; 7]) {
    let col = cell % ATLAS_COLS;
    let row = cell / ATLAS_COLS;
    let origin = ((row * CELL_PX * ATLAS_PX) + col * CELL_PX) as usize * 4;
    // 8x8 cell, glyph tucked in at (1, 0).
    for (y, line) in rows.iter().enumerate() {
        for (x, ch) in line.chars().enumerate() {
            if ch == '#' {
                let px = (x as u32 + 1).min(CELL_PX - 1);
                let py = y as u32;
                let p = origin + ((py * ATLAS_PX + px) * 4) as usize;
                atlas[p..p + 4].copy_from_slice(&[255, 255, 255, 255]);
            }
        }
    }
}

/// UV rectangle of the 8x8 glyph cell.
pub fn glyph_uv(cell: u32) -> [f32; 4] {
    let col = (cell % ATLAS_COLS) as f32;
    let row = (cell / ATLAS_COLS) as f32;
    let s = 1.0 / ATLAS_PX as f32;
    let inset = 0.25;
    [
        (col * TILE_PX as f32 + inset) * s,
        (row * TILE_PX as f32 + inset) * s,
        (col * TILE_PX as f32 + CELL_PX as f32 - inset) * s,
        (row * TILE_PX as f32 + CELL_PX as f32 - inset) * s,
    ]
}

/// Width in pixels of a text run when drawn at `scale`.
pub fn text_width(text: &str, scale: f32) -> f32 {
    // 6 px advance per character (5 px glyph + 1 px gap).
    text.chars().count() as f32 * 6.0 * scale
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_glyph_row_is_five_wide() {
        for (c, rows) in GLYPHS {
            for row in rows {
                assert_eq!(row.chars().count(), 5, "glyph {c:?} row {row:?}");
            }
        }
    }

    #[test]
    fn glyph_cells_are_unique_per_char() {
        for c in 32u8..=126 {
            let cell = glyph_cell(c as char);
            assert!(cell >= FONT_CELL_BASE);
        }
    }

    #[test]
    fn lowercase_maps_to_upper() {
        assert_eq!(glyph_cell('a'), glyph_cell('A'));
    }
}
